import { useEffect, useState } from 'react';
import { db, auth } from '../firebase';
import { collection, addDoc, serverTimestamp, updateDoc, doc } from 'firebase/firestore';
import { useSettings, UNCATEGORIZED_CATEGORY } from '../contexts/SettingsContext';
import { useGoals, GOAL_ICONS } from '../contexts/GoalsContext';
import { useCards, CARD_ICONS } from '../contexts/CardsContext';
import { INVESTMENT_TYPES, useInvestments } from '../contexts/InvestmentContext';
import { useAccess } from '../contexts/AccessContext';
import CurrencyInput from './ui/CurrencyInput';
import { generateTransactionHash, generateInstallmentGroupId } from '../services/installments';
import usePlannerGoals from '../pages/planner/usePlannerGoals';

export default function TransactionForm() {
  const { ownerId } = useAccess();
  const [type, setType] = useState('expense');
  const [description, setDescription] = useState('');
  const [amount, setAmount] = useState(0);
  const [category, setCategory] = useState('');
  const [selectedGoalId, setSelectedGoalId] = useState('');
  const [selectedPlannerGoalId, setSelectedPlannerGoalId] = useState('');
  const [selectedCardId, setSelectedCardId] = useState(null); // null = Cash/No Card
  const [loading, setLoading] = useState(false);
  // Date state - default to today
  const [transactionDate, setTransactionDate] = useState(new Date().toISOString().split('T')[0]);
  // Installment state
  const [isInstallment, setIsInstallment] = useState(false);
  const [currentInstallment, setCurrentInstallment] = useState(1);
  const [totalInstallments, setTotalInstallments] = useState(2);
  // Investment type state
  const [investmentType, setInvestmentType] = useState('fixed_income');

  const { categories, t, language } = useSettings();
  const { goals, addAmountToGoal, getGoalColor } = useGoals();
  const { cards, getCardColor } = useCards();
  const { addInvestment } = useInvestments();
  const isInvestmentCategory = category === 'Investments' || category === 'Investimentos';

  // Only show non-completed goals for linking
  const availableGoals = goals.filter(g => !g.completed);
  const plannerGoals = usePlannerGoals();

  useEffect(() => {
    if (isInvestmentCategory && isInstallment) {
      setIsInstallment(false);
    }
  }, [isInstallment, isInvestmentCategory]);

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!amount || amount <= 0) return;

    setLoading(true);

    try {
      // Find selected goal name for reference
      const selectedGoal = selectedGoalId ? goals.find(g => g.id === selectedGoalId) : null;
      const baseDate = new Date(transactionDate + 'T12:00:00'); // Use noon to avoid timezone issues
      const baseCategory = category; // Use selected category as-is, allow empty/"Sem Categoria"

      if (isInstallment && totalInstallments >= 2) {
        // Generate all installment transactions
        const installmentGroupId = generateInstallmentGroupId({
          description,
          amount: parseFloat(amount),
          date: baseDate.toISOString()
        });

        let totalInstallmentsCreated = 0;

        for (let i = currentInstallment; i <= totalInstallments; i++) {
          const installmentDate = new Date(baseDate);
          installmentDate.setMonth(installmentDate.getMonth() + (i - currentInstallment));

          const installmentDescription = `${description} (${i}/${totalInstallments})`;
          const transactionData = {
            userId: ownerId || auth.currentUser.uid,
            type,
            description: installmentDescription,
            amount: parseFloat(amount),
            category: baseCategory,
            createdAt: serverTimestamp(),
            date: installmentDate.toISOString(),
            goalId: selectedGoalId || null,
            goalName: selectedGoal?.name || null,
            plannerGoalId: selectedPlannerGoalId || null,
            cardId: selectedCardId || null,
            // Installment fields
            isInstallment: true,
            installmentCurrent: i,
            installmentTotal: totalInstallments,
            installmentGroupId,
            autoGenerated: i > currentInstallment,
            // Investment type (if category is Investments)
            investmentType: baseCategory === 'Investments' ? investmentType : null,
            metadata: { catSource: 'manual', catConfidence: 1.0, isCorrected: false, originalCategory: baseCategory }
          };

          transactionData.hash = generateTransactionHash(transactionData);
          await addDoc(collection(db, 'transactions'), transactionData);
          totalInstallmentsCreated++;
        }

        // If category is Investments and it's an expense, create an investment record
        // Income with Investments category = dividends/returns, not a new investment
        const isInvestment = baseCategory === 'Investments' || baseCategory === 'Investimentos';
        if (isInvestment && type === 'expense') {
          const totalInvestmentAmount = parseFloat(amount) * totalInstallmentsCreated;
          const investmentData = {
            name: description,
            type: investmentType,
            bank: selectedCardId || '',
            initialAmount: totalInvestmentAmount,
            currentAmount: totalInvestmentAmount,
            expectedReturn: 0,
            returnType: 'annual',
            purchaseDate: baseDate.toISOString().split('T')[0],
            maturityDate: null,
            goalId: selectedGoalId || null,
            notes: `Installment investment: ${totalInstallmentsCreated} payments of ${amount}`,
          };
          await addInvestment(investmentData, false);
        }

        // If linked to a goal, add to goal progress for ALL installments created
        // Investments contribute positively (you're saving money)
        if (selectedGoalId) {
          const amountPerInstallment = (type === 'income' || isInvestment) ? parseFloat(amount) : -parseFloat(amount);
          const totalAmountToAdd = amountPerInstallment * totalInstallmentsCreated;
          await addAmountToGoal(selectedGoalId, totalAmountToAdd);
        }
      } else {
        // Single transaction
        const transactionData = {
          userId: ownerId || auth.currentUser.uid,
          type,
          description,
          amount: parseFloat(amount),
          category: baseCategory,
          createdAt: serverTimestamp(),
          date: baseDate.toISOString(),
          goalId: selectedGoalId || null,
          goalName: selectedGoal?.name || null,
          plannerGoalId: selectedPlannerGoalId || null,
          cardId: selectedCardId || null,
          // Investment type (if category is Investments)
          investmentType: baseCategory === 'Investments' ? investmentType : null,
          metadata: { catSource: 'manual', catConfidence: 1.0, isCorrected: false, originalCategory: baseCategory }
        };

        transactionData.hash = generateTransactionHash(transactionData);
        const docRef = await addDoc(collection(db, 'transactions'), transactionData);

        // If category is Investments and it's an expense, create an investment record and link it
        // Income with Investments category = dividends/returns, not a new investment
        const isInvestment = baseCategory === 'Investments' || baseCategory === 'Investimentos';
        if (isInvestment && type === 'expense') {
          const investmentData = {
            name: description,
            type: investmentType,
            bank: selectedCardId || '',
            initialAmount: parseFloat(amount),
            currentAmount: parseFloat(amount),
            expectedReturn: 0,
            returnType: 'annual',
            purchaseDate: baseDate.toISOString().split('T')[0],
            maturityDate: null,
            goalId: selectedGoalId || null,
            notes: '',
          };

          const investmentId = await addInvestment(investmentData, false);

          // Link transaction to investment
          if (investmentId) {
            await updateDoc(doc(db, 'transactions', docRef.id), {
              investmentId: investmentId
            });
          }
        }

        // If linked to a goal, add to goal progress
        // Investments contribute positively (you're saving money), other expenses subtract
        if (selectedGoalId) {
          const amountToAdd = (type === 'income' || isInvestment) ? parseFloat(amount) : -parseFloat(amount);
          await addAmountToGoal(selectedGoalId, amountToAdd);
        }
      }

      // Reset form
      setDescription('');
      setAmount(0);
      setCategory('');
      setSelectedGoalId('');
      setSelectedPlannerGoalId('');
      setSelectedCardId(null);
      setTransactionDate(new Date().toISOString().split('T')[0]);
      setIsInstallment(false);
      setCurrentInstallment(1);
      setTotalInstallments(2);
      setInvestmentType('fixed_income');
    } catch (error) {
      console.error('Error adding transaction:', error);
      alert('Failed to add transaction. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="bg-white dark:bg-gray-800 border border-gray-100 dark:border-gray-700 rounded-2xl p-6 shadow-sm">
      <h2 className="text-lg font-bold text-gray-900 dark:text-white mb-6">{t('transactionForm.addTransaction')}</h2>

      <form onSubmit={handleSubmit} className="space-y-5">
        {/* Type Toggle */}
        <div className="flex p-1 bg-gray-100 dark:bg-gray-700 rounded-xl">
          <button
            type="button"
            onClick={() => setType('expense')}
            className={`flex-1 py-2.5 text-sm font-medium rounded-lg transition-all duration-200 ${
              type === 'expense'
                ? 'bg-white dark:bg-gray-600 text-gray-900 dark:text-white shadow-sm'
                : 'text-gray-500 dark:text-gray-400 hover:text-gray-700 dark:hover:text-gray-200'
            }`}
          >
            {t('transactionForm.expense')}
          </button>
          <button
            type="button"
            onClick={() => setType('income')}
            className={`flex-1 py-2.5 text-sm font-medium rounded-lg transition-all duration-200 ${
              type === 'income'
                ? 'bg-white dark:bg-gray-600 text-gray-900 dark:text-white shadow-sm'
                : 'text-gray-500 dark:text-gray-400 hover:text-gray-700 dark:hover:text-gray-200'
            }`}
          >
            {t('transactionForm.income')}
          </button>
        </div>

        {/* Amount */}
        <div>
          <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
            {t('transactionForm.amount')}
          </label>
          <CurrencyInput
            value={amount}
            onChange={setAmount}
          />
        </div>

        {/* Description */}
        <div>
          <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
            {t('transactionForm.description')}
          </label>
          <input
            type="text"
            value={description}
            onChange={(e) => setDescription(e.target.value)}
            required
            className="w-full px-4 py-3 bg-gray-50 dark:bg-gray-700 border border-gray-200 dark:border-gray-600 rounded-xl
              text-gray-900 dark:text-white placeholder-gray-400
              focus:bg-white dark:focus:bg-gray-600 focus:border-gray-900 dark:focus:border-gray-500 focus:ring-0 focus:outline-none
              transition-all duration-200"
            placeholder={t('transactionForm.descriptionPlaceholder')}
          />
        </div>

        {/* Date */}
        <div>
          <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
            {t('transactionForm.date')}
          </label>
          <input
            type="date"
            lang={language === 'pt' ? 'pt-BR' : 'en-US'}
            value={transactionDate}
            onChange={(e) => setTransactionDate(e.target.value)}
            className="w-full px-4 py-3 bg-gray-50 dark:bg-gray-700 border border-gray-200 dark:border-gray-600 rounded-xl
              text-gray-900 dark:text-white
              focus:bg-white dark:focus:bg-gray-600 focus:border-gray-900 dark:focus:border-gray-500 focus:ring-0 focus:outline-none
              transition-all duration-200"
          />
        </div>

        {/* Category */}
        <div>
          <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
            {t('transactionForm.category')}
          </label>
          <select
            value={category}
            onChange={(e) => setCategory(e.target.value)}
            className="w-full pl-4 pr-10 py-3 bg-gray-50 dark:bg-gray-700 border border-gray-200 dark:border-gray-600 rounded-xl
              text-gray-900 dark:text-white
              focus:bg-white dark:focus:bg-gray-600 focus:border-gray-900 dark:focus:border-gray-500 focus:ring-0 focus:outline-none
              transition-all duration-200 appearance-none cursor-pointer"
            style={{
              backgroundImage: `url("data:image/svg+xml,%3csvg xmlns='http://www.w3.org/2000/svg' fill='none' viewBox='0 0 20 20'%3e%3cpath stroke='%236b7280' stroke-linecap='round' stroke-linejoin='round' stroke-width='1.5' d='M6 8l4 4 4-4'/%3e%3c/svg%3e")`,
              backgroundPosition: 'right 12px center',
              backgroundRepeat: 'no-repeat',
              backgroundSize: '20px'
            }}
          >
            {(() => {
              const uncatName = UNCATEGORIZED_CATEGORY[language] || UNCATEGORIZED_CATEGORY.pt;
              const all = categories[type] || [];
              const uncatEntry = all.find(c => c === uncatName);
              const rest = all.filter(c => c !== uncatName).sort((a, b) => a.localeCompare(b));
              return (<>
                {uncatEntry && <option value={uncatEntry}>{uncatEntry}</option>}
                {uncatEntry && <optgroup label="──────────────" />}
                {rest.map(cat => <option key={cat} value={cat}>{cat}</option>)}
              </>);
            })()}
          </select>
        </div>

        {/* Investment Type (only shown when category is Investments) */}
        {(category === 'Investments' || category === 'Investimentos') && (
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
              {t('investments.type')}
            </label>
            <div className="grid grid-cols-5 gap-2">
              {Object.entries(INVESTMENT_TYPES).map(([key, info]) => (
                <button
                  key={key}
                  type="button"
                  onClick={() => setInvestmentType(key)}
                  className={`p-3 text-xl rounded-xl border-2 transition flex flex-col items-center gap-1 ${
                    investmentType === key
                      ? 'border-gray-900 dark:border-gray-400 bg-gray-100 dark:bg-gray-700'
                      : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                  }`}
                  title={t(`investments.types.${key}`)}
                >
                  <span>{info.icon}</span>
                  <span className="text-[10px] text-gray-500 dark:text-gray-400 truncate w-full text-center">
                    {t(`investments.types.${key}`)}
                  </span>
                </button>
              ))}
            </div>
          </div>
        )}

        {/* Card Selector */}
        <div>
          <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
            {t('cards.filterByCard')}
          </label>
          <div className="space-y-2 max-h-48 overflow-y-auto">
            {/* Cash / No Card option */}
            <button
              type="button"
              onClick={() => setSelectedCardId(null)}
              className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                selectedCardId === null
                  ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                  : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
              }`}
            >
              <div className="w-8 h-8 bg-gray-100 dark:bg-gray-600 rounded-lg flex items-center justify-center text-base">
                {CARD_ICONS.other}
              </div>
              <span className="text-sm text-gray-600 dark:text-gray-300">{t('cards.cashNoCard')}</span>
            </button>

            {/* Card options */}
            {cards.map((card) => {
              const color = getCardColor(card.color);
              const icon = CARD_ICONS[card.icon] || (card.type === 'debit' ? CARD_ICONS.debit : CARD_ICONS.credit);
              return (
                <button
                  key={card.id}
                  type="button"
                  onClick={() => setSelectedCardId(card.id)}
                  className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                    selectedCardId === card.id
                      ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                      : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                  }`}
                >
                  <div className={`w-8 h-8 ${color.light} rounded-lg flex items-center justify-center text-base`}>
                    {icon}
                  </div>
                  <div className="flex-1 text-left">
                    <span className="text-sm font-medium text-gray-900 dark:text-white">{card.name}</span>
                    {card.lastDigits && (
                      <span className="text-xs text-gray-400 ml-1">****{card.lastDigits}</span>
                    )}
                  </div>
                  <span className={`px-2 py-0.5 text-xs rounded-full ${
                    card.type === 'credit'
                      ? 'bg-purple-100 text-purple-700 dark:bg-purple-900/30 dark:text-purple-300'
                      : 'bg-blue-100 text-blue-700 dark:bg-blue-900/30 dark:text-blue-300'
                  }`}>
                    {card.type === 'credit' ? t('cards.creditCard') : t('cards.bankAccount')}
                  </span>
                </button>
              );
            })}
          </div>
        </div>

        {/* Installment Toggle (only for expenses) */}
        {type === 'expense' && !isInvestmentCategory && (
          <div className="space-y-3">
            <button
              type="button"
              onClick={() => setIsInstallment(!isInstallment)}
              className={`w-full flex items-center justify-between p-3 rounded-xl border transition-all ${
                isInstallment
                  ? 'border-blue-500 bg-blue-50 dark:bg-blue-900/30'
                  : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
              }`}
            >
              <div className="flex items-center gap-3">
                <div className={`w-8 h-8 rounded-lg flex items-center justify-center ${
                  isInstallment ? 'bg-blue-100 dark:bg-blue-800 text-blue-600' : 'bg-gray-100 dark:bg-gray-600 text-gray-400'
                }`}>
                  <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 7V3m8 4V3m-9 8h10M5 21h14a2 2 0 002-2V7a2 2 0 00-2-2H5a2 2 0 00-2 2v12a2 2 0 002 2z" />
                  </svg>
                </div>
                <span className={`text-sm font-medium ${isInstallment ? 'text-blue-700 dark:text-blue-300' : 'text-gray-700 dark:text-gray-300'}`}>
                  {t('transactionForm.isInstallment')}
                </span>
              </div>
              <div className={`w-12 h-7 rounded-full transition-colors flex items-center px-1.5 ${
                isInstallment ? 'bg-blue-500' : 'bg-gray-200 dark:bg-gray-600'
              }`}>
                <div className={`w-4 h-4 bg-white rounded-full shadow transition-transform ${
                  isInstallment ? 'translate-x-5' : 'translate-x-0'
                }`} />
              </div>
            </button>

            {/* Installment Fields */}
            {isInstallment && (
              <div className="p-4 bg-blue-50 dark:bg-blue-900/30 rounded-xl space-y-3">
                <div className="flex items-center gap-3">
                  <div className="flex-1">
                    <label className="block text-xs font-medium text-blue-700 dark:text-blue-300 mb-1">
                      {t('transactionForm.currentInstallment')}
                    </label>
                    <input
                      type="number"
                      min="1"
                      max={totalInstallments}
                      value={currentInstallment}
                      onChange={(e) => setCurrentInstallment(Math.max(1, Math.min(parseInt(e.target.value) || 1, totalInstallments)))}
                      className="w-full px-3 py-2 bg-white dark:bg-gray-700 border border-blue-200 dark:border-blue-700 rounded-lg text-center text-gray-900 dark:text-white
                        focus:border-blue-500 focus:ring-0 focus:outline-none"
                    />
                  </div>
                  <span className="text-blue-600 dark:text-blue-400 font-medium pt-5">{t('transactionForm.installmentOf')}</span>
                  <div className="flex-1">
                    <label className="block text-xs font-medium text-blue-700 dark:text-blue-300 mb-1">
                      {t('transactionForm.totalInstallments')}
                    </label>
                    <input
                      type="number"
                      min="2"
                      max="48"
                      value={totalInstallments}
                      onChange={(e) => {
                        const newTotal = Math.max(2, Math.min(parseInt(e.target.value) || 2, 48));
                        setTotalInstallments(newTotal);
                        if (currentInstallment > newTotal) setCurrentInstallment(newTotal);
                      }}
                      className="w-full px-3 py-2 bg-white dark:bg-gray-700 border border-blue-200 dark:border-blue-700 rounded-lg text-center text-gray-900 dark:text-white
                        focus:border-blue-500 focus:ring-0 focus:outline-none"
                    />
                  </div>
                </div>
                <p className="text-xs text-blue-600 dark:text-blue-400">
                  {t('transactionForm.futureInstallmentsNote')}
                </p>
              </div>
            )}
          </div>
        )}

        {/* Link to Goal */}
        {availableGoals.length > 0 && (
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
              {t('goals.linkToGoal')}
            </label>
            <div className="space-y-2">
              {/* No goal option */}
              <button
                type="button"
                onClick={() => setSelectedGoalId('')}
                className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                  !selectedGoalId
                    ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                    : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                }`}
              >
                <div className="w-8 h-8 bg-gray-100 dark:bg-gray-600 rounded-lg flex items-center justify-center text-gray-400">
                  <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                  </svg>
                </div>
                <span className="text-sm text-gray-600 dark:text-gray-300">{t('goals.noGoalSelected')}</span>
              </button>

              {/* Goal options */}
              {availableGoals.map((goal) => {
                const color = getGoalColor(goal.color);
                const icon = GOAL_ICONS[goal.icon] || GOAL_ICONS.other;
                return (
                  <button
                    key={goal.id}
                    type="button"
                    onClick={() => setSelectedGoalId(goal.id)}
                    className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                      selectedGoalId === goal.id
                        ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                        : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                    }`}
                  >
                    <div className={`w-8 h-8 ${color.light} rounded-lg flex items-center justify-center text-base`}>
                      {icon}
                    </div>
                    <span className="text-sm font-medium text-gray-900 dark:text-white">{goal.name}</span>
                  </button>
                );
              })}
            </div>
          </div>
        )}

        {/* Planner goal link */}
        {plannerGoals.length > 0 && (
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
              Objetivo do planner
            </label>
            <select
              value={selectedPlannerGoalId}
              onChange={e => setSelectedPlannerGoalId(e.target.value)}
              className="w-full px-4 py-3 bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-xl text-gray-900 dark:text-white focus:border-blue-500 dark:focus:border-blue-400 focus:ring-2 focus:ring-blue-500/20 focus:outline-none transition text-sm"
            >
              <option value="">Nenhum</option>
              {plannerGoals.map(g => (
                <option key={g.id} value={g.id}>
                  {g.layerLabel ? `${g.layerLabel} › ${g.label}` : g.label}
                </option>
              ))}
            </select>
          </div>
        )}

        {/* Submit Button */}
        <button
          type="submit"
          disabled={loading || !amount || amount <= 0}
          className={`w-full py-3.5 rounded-xl font-medium text-white transition-all duration-200
            disabled:opacity-50 disabled:cursor-not-allowed
            ${type === 'expense'
              ? 'bg-rose-500 hover:bg-rose-600 active:bg-rose-700'
              : 'bg-emerald-500 hover:bg-emerald-600 active:bg-emerald-700'
            }`}
        >
          {loading ? (
            <span className="flex items-center justify-center gap-2">
              <svg className="animate-spin w-4 h-4" viewBox="0 0 24 24">
                <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" fill="none" />
                <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z" />
              </svg>
              {t('transactionForm.adding')}
            </span>
          ) : (
            `${t('common.add')} ${type === 'expense' ? t('transactionForm.expense') : t('transactionForm.income')}`
          )}
        </button>
      </form>
    </div>
  );
}
