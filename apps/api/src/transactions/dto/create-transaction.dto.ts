import { PartialType } from '@nestjs/mapped-types';
import {
  IsBoolean,
  IsDateString,
  IsIn,
  IsInt,
  IsObject,
  IsOptional,
  IsString,
  IsUUID,
  Min,
} from 'class-validator';

export class CreateTransactionDto {
  @IsString()
  amount: string;

  @IsIn(['income', 'expense'])
  type: 'income' | 'expense';

  @IsDateString()
  date: string;

  @IsOptional()
  @IsString()
  description?: string;

  @IsOptional()
  @IsString()
  category?: string;

  @IsOptional()
  @IsUUID()
  categoryId?: string;

  @IsOptional()
  @IsString()
  bankId?: string;

  @IsOptional()
  @IsUUID()
  accountId?: string;

  @IsOptional()
  @IsString()
  paymentMethod?: string;

  @IsOptional()
  @IsBoolean()
  ignored?: boolean;

  @IsOptional()
  @IsString()
  goalId?: string;

  @IsOptional()
  @IsString()
  goalName?: string;

  @IsOptional()
  @IsString()
  plannerGoalId?: string;

  @IsOptional()
  @IsString()
  investmentId?: string;

  @IsOptional()
  @IsString()
  investmentType?: string;

  @IsOptional()
  @IsBoolean()
  isInstallment?: boolean;

  @IsOptional()
  @IsInt()
  @Min(1)
  installmentCurrent?: number;

  @IsOptional()
  @IsInt()
  @Min(1)
  installmentTotal?: number;

  @IsOptional()
  @IsString()
  installmentGroupId?: string;

  @IsOptional()
  @IsBoolean()
  autoGenerated?: boolean;

  @IsOptional()
  @IsBoolean()
  isRecurring?: boolean;

  @IsOptional()
  @IsString()
  recurrenceFrequency?: string;

  @IsOptional()
  @IsDateString()
  recurrenceEndDate?: string;

  @IsOptional()
  @IsString()
  hash?: string;

  @IsOptional()
  @IsString()
  dedupHash?: string;

  @IsOptional()
  @IsString()
  source?: string;

  @IsOptional()
  @IsObject()
  metadata?: Record<string, unknown>;
}

export class UpdateTransactionDto extends PartialType(CreateTransactionDto) {}
