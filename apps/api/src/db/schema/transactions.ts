import { pgTable, uuid, varchar, numeric, date, timestamp, boolean, integer, jsonb } from 'drizzle-orm/pg-core';
import { transactionTypeEnum } from './enums';
import { users } from './users';
import { categories } from './categories';
import { accounts } from './accounts';

export const transactions = pgTable('transactions', {
  id: uuid('id').primaryKey().defaultRandom(),
  clientId: varchar('client_id').notNull(),
  userId: uuid('user_id').notNull().references(() => users.id),
  firebaseDocId: varchar('firebase_doc_id').unique(),
  amount: numeric('amount', { precision: 12, scale: 2 }).notNull(),
  type: transactionTypeEnum('type').notNull(),
  description: varchar('description'),
  date: date('date').notNull(),
  category: varchar('category'),
  categoryId: uuid('category_id').references(() => categories.id),
  bankId: varchar('bank_id'),
  accountId: uuid('account_id').references(() => accounts.id),
  paymentMethod: varchar('payment_method'),
  ignored: boolean('ignored').default(false).notNull(),
  goalId: varchar('goal_id'),
  goalName: varchar('goal_name'),
  plannerGoalId: varchar('planner_goal_id'),
  investmentId: varchar('investment_id'),
  investmentType: varchar('investment_type'),
  isInstallment: boolean('is_installment').default(false).notNull(),
  installmentCurrent: integer('installment_current'),
  installmentTotal: integer('installment_total'),
  installmentGroupId: varchar('installment_group_id'),
  autoGenerated: boolean('auto_generated').default(false).notNull(),
  isRecurring: boolean('is_recurring').default(false).notNull(),
  recurrenceFrequency: varchar('recurrence_frequency'),
  recurrenceEndDate: timestamp('recurrence_end_date', { withTimezone: true }),
  importId: uuid('import_id'),
  hash: varchar('hash'),
  dedupHash: varchar('dedup_hash'),
  source: varchar('source'),
  metadata: jsonb('metadata'),
  // Soft delete: rows are hidden, never destroyed. Every read path must filter on this.
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
});
