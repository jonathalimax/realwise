type Row = Record<string, unknown>;

function toDate(val: unknown): Date | null {
  if (!val) return null;
  if (typeof val === 'object' && val !== null && 'toDate' in val && typeof (val as { toDate: unknown }).toDate === 'function') {
    return (val as { toDate: () => Date }).toDate();
  }
  if (val instanceof Date) return val;
  return new Date(val as string);
}

function toNumericString(val: unknown): string | null {
  if (val === undefined || val === null) return null;
  return String(val);
}

const INVESTMENT_TYPE_MAP: Record<string, string> = {
  stocks: 'stocks',
  stock: 'stocks',
  acoes: 'stocks',
  acoes_dividendos: 'stocks',
  fii: 'fii',
  fiis: 'fii',
  etf: 'etf',
  etfs: 'etf',
  fixed: 'fixed_income',
  fixed_income: 'fixed_income',
  renda_fixa: 'fixed_income',
  'renda fixa': 'fixed_income',
  crypto: 'crypto',
  funds: 'funds',
  fund: 'funds',
  fundos: 'funds',
  real_estate: 'real_estate',
  realestate: 'real_estate',
  imovel: 'real_estate',
  imoveis: 'real_estate',
  property: 'real_estate',
};
function mapInvestmentType(val: string): string {
  if (!val) return 'other';
  return INVESTMENT_TYPE_MAP[val.toLowerCase()] ?? 'other';
}

function toStrOrNull(val: unknown): string | null {
  if (val === undefined || val === null || val === '') return null;
  return String(val);
}

export function transformUser(docId: string, data: Row, clientId: string) {
  return {
    clientId,
    email: data.email as string,
    name: (data.name as string) ?? null,
    profileImageUrl: (data.profileImageUrl as string) ?? (data.photoURL as string) ?? null,
    firebaseUid: docId,
    role: 'user' as const,
  };
}

export function transformAccount(docId: string, data: Row, clientId: string, userId: string) {
  const bankId = toStrOrNull(data.bankId);
  const cardName = toStrOrNull(data.cardName);
  const customBankName = toStrOrNull(data.customBankName);
  const hasCredit = Boolean(data.hasCredit);

  const type = data.hasCredit ? 'credit' : (toStrOrNull(data.type) ?? 'checking');
  return {
    clientId,
    userId,
    firebaseDocId: docId,
    name: cardName ?? customBankName ?? bankId ?? 'Unknown',
    type: type as 'checking' | 'savings' | 'credit' | 'investment' | 'wallet',
    bankId,
    cardName,
    customBankName,
    hasCredit,
    closingDay: (data.closingDay as number) ?? null,
    paymentDay: (data.paymentDay as number) ?? null,
    color: toStrOrNull(data.color),
    icon: toStrOrNull(data.icon) ?? bankId,
    balance: toNumericString(data.balance),
  };
}

