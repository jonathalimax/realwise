/**
 * Server-side file parser for bank statements
 * Handles CSV and Excel files from Firebase Storage
 */

const { parse } = require('csv-parse/sync');
const XLSX = require('xlsx');
const {
  detectNubank, parseNubankStatement,
  detectItau, parseItauStatement,
  detectBradesco, parseBradescoStatement,
  parseGenericStatement
} = require('./bankParsers');
const { categorizeTransaction } = require('./categorization');
const {
  detectInstallment,
  generateInstallmentTransactions,
  generateTransactionHash,
  generateInstallmentGroupId
} = require('./installments');

/**
 * Parse file content from Buffer
 * @param {Buffer} fileBuffer - File content as Buffer
 * @param {string} fileName - Original file name (for extension detection)
 * @param {string} bankType - Bank type ('auto', 'nubank', 'itau', 'bradesco', 'generic')
 * @returns {Array} - Processed transactions
 */
function parseFileFromBuffer(fileBuffer, fileName, bankType = 'auto') {
  const fileExtension = fileName.split('.').pop().toLowerCase();

  let data = [];

  if (fileExtension === 'csv') {
    data = parseCSVFromBuffer(fileBuffer);
  } else if (['xlsx', 'xls'].includes(fileExtension)) {
    data = parseExcelFromBuffer(fileBuffer);
  } else {
    throw new Error('Unsupported file format. Please use CSV or Excel files.');
  }

  if (data.length === 0) {
    throw new Error('No data found in the file.');
  }

  // Parse based on bank type
  let transactions = [];

  if (bankType === 'auto') {
    const headers = Object.keys(data[0]);
    if (detectNubank(headers)) {
      transactions = parseNubankStatement(data);
      bankType = 'nubank';
    } else if (detectItau(headers)) {
      transactions = parseItauStatement(data);
      bankType = 'itau';
    } else if (detectBradesco(headers)) {
      transactions = parseBradescoStatement(data);
      bankType = 'bradesco';
    } else {
      transactions = parseGenericStatement(data);
      bankType = 'generic';
    }
  } else {
    switch (bankType) {
      case 'nubank':
        transactions = parseNubankStatement(data);
        break;
      case 'itau':
        transactions = parseItauStatement(data);
        break;
      case 'bradesco':
        transactions = parseBradescoStatement(data);
        break;
      default:
        transactions = parseGenericStatement(data);
        bankType = 'generic';
    }
  }

  // Apply categorization and detect installments
  const processedTransactions = [];

  for (const t of transactions) {
    const categorization = categorizeTransaction(t.description);
    const installmentInfo = detectInstallment(t.description);

    const baseTransaction = {
      ...t,
      category: categorization?.category || null, // null = needs review
      type: categorization?.type || t.type,
      autoCategory: !!categorization,
      categoryConfidence: categorization?.confidence || 0,
      needsReview: !categorization, // Mark for review if no auto-categorization
      hash: generateTransactionHash(t)
    };

    if (installmentInfo) {
      // Generate all future installments
      baseTransaction.installmentGroupId = generateInstallmentGroupId(baseTransaction);
      const installmentTransactions = generateInstallmentTransactions(
        baseTransaction,
        installmentInfo.current,
        installmentInfo.total
      );

      // Apply categorization to all installments and mark as auto-generated
      installmentTransactions.forEach((installment, index) => {
        installment.hash = generateTransactionHash(installment);
        installment.autoGenerated = index > 0;
        processedTransactions.push(installment);
      });
    } else {
      processedTransactions.push(baseTransaction);
    }
  }

  return {
    transactions: processedTransactions,
    detectedBankType: bankType
  };
}

/**
 * Parse CSV from Buffer
 */
function parseCSVFromBuffer(buffer) {
  const content = buffer.toString('utf-8');

  // Detect delimiter: Brazilian CSVs often use semicolon
  const firstLine = content.split('\n')[0];
  const semicolonCount = (firstLine.match(/;/g) || []).length;
  const commaCount = (firstLine.match(/,/g) || []).length;
  const delimiter = semicolonCount > commaCount ? ';' : ',';

  const records = parse(content, {
    columns: true,
    skip_empty_lines: true,
    delimiter: delimiter,
    trim: true,
    relax_quotes: true,
    relax_column_count: true
  });

  return records;
}

/**
 * Parse Excel from Buffer
 */
function parseExcelFromBuffer(buffer) {
  const workbook = XLSX.read(buffer, { type: 'buffer' });
  const firstSheetName = workbook.SheetNames[0];
  const worksheet = workbook.Sheets[firstSheetName];
  const jsonData = XLSX.utils.sheet_to_json(worksheet, { defval: '' });
  return jsonData;
}

/**
 * Detect bank type from folder path
 * @param {string} filePath - Storage file path
 * @returns {string} - Bank type
 */
function detectBankTypeFromPath(filePath) {
  const pathLower = filePath.toLowerCase();

  if (pathLower.includes('/nubank/')) return 'nubank';
  if (pathLower.includes('/itau/')) return 'itau';
  if (pathLower.includes('/bradesco/')) return 'bradesco';
  if (pathLower.includes('/other/') || pathLower.includes('/generic/')) return 'generic';

  return 'auto';
}

