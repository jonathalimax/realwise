import { useState, useCallback, useEffect } from 'react';
import { db, auth } from '../firebase';
import { collection, addDoc, serverTimestamp, query, where, getDocs } from 'firebase/firestore';
import { parseFile, BANK_OPTIONS } from '../services/importers';
import { useSettings } from '../contexts/SettingsContext';
import { useCards, CARD_ICONS } from '../contexts/CardsContext';
import { generateTransactionHash } from '../services/installments';

export default function ImportModal({ isOpen, onClose }) {
  const [file, setFile] = useState(null);
  const [bankType, setBankType] = useState('auto');
  const [selectedCardId, setSelectedCardId] = useState(null); // null = Cash/No Card
  const [transactions, setTransactions] = useState([]);
  const [loading, setLoading] = useState(false);
  const [importing, setImporting] = useState(false);
  const [error, setError] = useState('');
  const [step, setStep] = useState('upload'); // upload, preview, done
  const [existingHashes, setExistingHashes] = useState(new Set());
  const [duplicateCount, setDuplicateCount] = useState(0);
  const [installmentCount, setInstallmentCount] = useState(0);

  const { formatCurrency, categories, t, language } = useSettings();
  const { cards, getCardColor } = useCards();

  const locale = language === 'pt' ? 'pt-BR' : 'en-US';

  // Load existing transaction hashes when modal opens
  useEffect(() => {
    if (isOpen && auth.currentUser) {
      loadExistingHashes();
    }
  }, [isOpen]);

  const loadExistingHashes = async () => {
    try {
      const q = query(
        collection(db, 'transactions'),
        where('userId', '==', auth.currentUser.uid)
      );
      const snapshot = await getDocs(q);
      const hashes = new Set();

      snapshot.docs.forEach(doc => {
        const data = doc.data();
        // Use stored hash or generate one
        if (data.hash) {
          hashes.add(data.hash);
        } else {
          // Generate hash for legacy transactions
          const hash = generateTransactionHash({
            date: data.date,
            description: data.description,
            amount: data.amount
          });
          hashes.add(hash);
        }
      });

      setExistingHashes(hashes);
    } catch (err) {
      console.error('Error loading existing hashes:', err);
    }
  };

  const bankLabels = {
    auto: t('import.autoDetect'),
    nubank: 'Nubank',
    itau: 'Itaú',
    bradesco: 'Bradesco',
    generic: t('import.generic')
  };

  const handleDrop = useCallback((e) => {
    e.preventDefault();
    const droppedFile = e.dataTransfer?.files[0] || e.target.files?.[0];
    if (droppedFile) {
      setFile(droppedFile);
      setError('');
    }
  }, []);

  const handleParse = async () => {
    if (!file) return;

    setLoading(true);
    setError('');

    try {
      const parsed = await parseFile(file, bankType);

      // Mark duplicates and count stats
      let duplicates = 0;
      let installments = 0;

      const processedTransactions = parsed.map(t => {
        const isDuplicate = existingHashes.has(t.hash);
        if (isDuplicate) duplicates++;
        if (t.isInstallment) installments++;

        return {
          ...t,
          isDuplicate,
          selected: !isDuplicate // Pre-select non-duplicates
        };
      });

      setDuplicateCount(duplicates);
      setInstallmentCount(installments);
      setTransactions(processedTransactions);
      setStep('preview');
    } catch (err) {
      setError(err.message || 'Failed to parse file');
    } finally {
      setLoading(false);
    }
  };

  const handleImport = async () => {
    setImporting(true);

    try {
      // Only import selected transactions
      const toImport = transactions.filter(t => t.selected);

      for (const t of toImport) {
        await addDoc(collection(db, 'transactions'), {
          userId: auth.currentUser.uid,
          type: t.type,
          description: t.description,
          amount: t.amount,
          category: t.category,
          createdAt: serverTimestamp(),
          date: t.date,
          imported: true,
          hash: t.hash,
          cardId: selectedCardId || null,
          // Installment fields
          isInstallment: t.isInstallment || false,
          installmentCurrent: t.installmentCurrent || null,
          installmentTotal: t.installmentTotal || null,
          installmentGroupId: t.installmentGroupId || null,
          autoGenerated: t.autoGenerated || false
        });
      }

      setStep('done');
    } catch (err) {
      setError(err.message || 'Failed to import transactions');
    } finally {
      setImporting(false);
    }
  };

  const toggleTransactionSelection = (index) => {
    setTransactions(prev => prev.map((t, i) =>
      i === index ? { ...t, selected: !t.selected } : t
    ));
  };

  const toggleTransactionType = (index) => {
    setTransactions(prev => prev.map((t, i) =>
      i === index ? { ...t, type: t.type === 'income' ? 'expense' : 'income' } : t
    ));
  };

  const swapAllTypes = () => {
    setTransactions(prev => prev.map(t => ({
      ...t,
      type: t.type === 'income' ? 'expense' : 'income'
    })));
  };

  const selectedCount = transactions.filter(t => t.selected).length;

  const handleClose = () => {
    setFile(null);
    setTransactions([]);
    setStep('upload');
    setError('');
    setDuplicateCount(0);
    setInstallmentCount(0);
    setSelectedCardId(null);
    onClose();
  };

  const updateTransactionCategory = (index, category) => {
    setTransactions(prev => prev.map((t, i) =>
      i === index ? { ...t, category, autoCategory: false } : t
    ));
  };

  const removeTransaction = (index) => {
    setTransactions(prev => prev.filter((_, i) => i !== index));
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50">
      <div className="bg-white dark:bg-gray-800 rounded-2xl w-full max-w-4xl max-h-[90vh] flex flex-col overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-100 dark:border-gray-700">
          <h2 className="text-xl font-semibold text-gray-900 dark:text-white">{t('import.title')}</h2>
          <button
            onClick={handleClose}
            className="p-2 text-gray-400 hover:text-gray-600 dark:hover:text-gray-200 hover:bg-gray-100 dark:hover:bg-gray-700 rounded-lg transition-colors"
          >
            <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6">
          {step === 'upload' && (
            <div className="space-y-6">
              {/* Bank Selection */}
              <div>
                <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
                  {t('import.bankFormat')}
                </label>
                <select
                  value={bankType}
                  onChange={(e) => setBankType(e.target.value)}
                  className="w-full px-4 py-3 bg-gray-50 dark:bg-gray-700 border border-gray-200 dark:border-gray-600 rounded-xl
                    text-gray-900 dark:text-white
                    focus:bg-white dark:focus:bg-gray-600 focus:border-gray-900 dark:focus:border-gray-500 focus:ring-0 focus:outline-none transition-all"
                >
                  {BANK_OPTIONS.map(opt => (
                    <option key={opt.value} value={opt.value}>
                      {bankLabels[opt.value] || opt.label}
                    </option>
                  ))}
                </select>
              </div>

              {/* Card Selection */}
              <div>
                <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
                  {t('cards.filterByCard')}
                </label>
                <div className="space-y-2 max-h-48 overflow-y-auto">
                  {/* Cash / No Card option */}
                  <button
                    type="button"
                    onClick={() => setSelectedCardId(null)}
                    className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                      selectedCardId === null
                        ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                        : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                    }`}
                  >
                    <div className="w-8 h-8 bg-gray-100 dark:bg-gray-600 rounded-lg flex items-center justify-center text-base">
                      {CARD_ICONS.other}
                    </div>
                    <span className="text-sm text-gray-600 dark:text-gray-300">{t('cards.cashNoCard')}</span>
                  </button>

                  {/* Card options */}
                  {cards.map((card) => {
                    const color = getCardColor(card.color);
                    const icon = CARD_ICONS[card.icon] || (card.type === 'debit' ? CARD_ICONS.debit : CARD_ICONS.credit);
                    return (
                      <button
                        key={card.id}
                        type="button"
                        onClick={() => setSelectedCardId(card.id)}
                        className={`w-full flex items-center gap-3 p-3 rounded-xl border transition-all ${
                          selectedCardId === card.id
                            ? 'border-gray-900 dark:border-gray-400 bg-gray-50 dark:bg-gray-700'
                            : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                        }`}
                      >
                        <div className={`w-8 h-8 ${color.light} rounded-lg flex items-center justify-center text-base`}>
                          {icon}
                        </div>
                        <div className="flex-1 text-left">
                          <span className="text-sm font-medium text-gray-900 dark:text-white">{card.name}</span>
                          {card.lastDigits && (
                            <span className="text-xs text-gray-400 ml-1">****{card.lastDigits}</span>
                          )}
                        </div>
                        <span className={`px-2 py-0.5 text-xs rounded-full ${
                          card.type === 'credit'
                            ? 'bg-purple-100 dark:bg-purple-900/40 text-purple-700 dark:text-purple-300'
                            : 'bg-blue-100 dark:bg-blue-900/40 text-blue-700 dark:text-blue-300'
                        }`}>
                          {card.type === 'credit' ? t('cards.creditCard') : t('cards.bankAccount')}
                        </span>
                      </button>
                    );
                  })}
                </div>
              </div>

              {/* Drop Zone */}
              <div
                onDrop={handleDrop}
                onDragOver={(e) => e.preventDefault()}
                className={`border-2 border-dashed rounded-2xl p-8 text-center transition-colors
                  ${file ? 'border-emerald-300 dark:border-emerald-600 bg-emerald-50 dark:bg-emerald-900/30' : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'}`}
              >
                {file ? (
                  <div className="space-y-2">
                    <div className="w-12 h-12 bg-emerald-100 dark:bg-emerald-900/50 rounded-full flex items-center justify-center mx-auto">
                      <svg className="w-6 h-6 text-emerald-600 dark:text-emerald-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
                      </svg>
                    </div>
                    <p className="font-medium text-gray-900 dark:text-white">{file.name}</p>
                    <button
                      onClick={() => setFile(null)}
                      className="text-sm text-gray-500 dark:text-gray-400 hover:text-gray-700 dark:hover:text-gray-200"
                    >
                      {t('common.remove')}
                    </button>
                  </div>
                ) : (
                  <div className="space-y-4">
                    <div className="w-12 h-12 bg-gray-100 dark:bg-gray-700 rounded-full flex items-center justify-center mx-auto">
                      <svg className="w-6 h-6 text-gray-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-8l-4-4m0 0L8 8m4-4v12" />
                      </svg>
                    </div>
                    <div>
                      <p className="font-medium text-gray-900 dark:text-white">{t('import.dropFile')}</p>
                      <p className="text-sm text-gray-500 dark:text-gray-400">{t('import.orClick')}</p>
                    </div>
                    <input
                      type="file"
                      accept=".csv,.xlsx,.xls"
                      onChange={handleDrop}
                      className="absolute inset-0 w-full h-full opacity-0 cursor-pointer"
                      style={{ position: 'relative' }}
                    />
                  </div>
                )}
              </div>

              {error && (
                <div className="p-4 bg-rose-50 dark:bg-rose-900/30 border border-rose-200 dark:border-rose-800 rounded-xl">
                  <p className="text-sm text-rose-600 dark:text-rose-400">{error}</p>
                </div>
              )}
            </div>
          )}

          {step === 'preview' && (
            <div className="space-y-4">
              {/* Stats */}
              <div className="flex flex-wrap items-center gap-3">
                <span className="px-3 py-1 bg-gray-100 dark:bg-gray-700 rounded-full text-sm text-gray-700 dark:text-gray-300">
                  {transactions.length} {language === 'pt' ? 'encontradas' : 'found'}
                </span>
                {duplicateCount > 0 && (
                  <span className="px-3 py-1 bg-amber-100 dark:bg-amber-900/40 text-amber-700 dark:text-amber-300 rounded-full text-sm">
                    {duplicateCount} {language === 'pt' ? 'duplicadas' : 'duplicates'}
                  </span>
                )}
                {installmentCount > 0 && (
                  <span className="px-3 py-1 bg-blue-100 dark:bg-blue-900/40 text-blue-700 dark:text-blue-300 rounded-full text-sm">
                    {installmentCount} {language === 'pt' ? 'parcelas' : 'installments'}
                  </span>
                )}
                <button
                  onClick={swapAllTypes}
                  className="px-3 py-1 bg-purple-100 dark:bg-purple-900/40 text-purple-700 dark:text-purple-300 rounded-full text-sm hover:bg-purple-200 dark:hover:bg-purple-900/60 transition-colors"
                  title={language === 'pt' ? 'Inverter todos os tipos' : 'Swap all types'}
                >
                  ↕️ {language === 'pt' ? 'Inverter tipos' : 'Swap types'}
                </button>
                <button
                  onClick={() => setStep('upload')}
                  className="ml-auto text-sm text-gray-500 dark:text-gray-400 hover:text-gray-700 dark:hover:text-gray-200"
                >
                  {t('common.back')}
                </button>
              </div>

              <div className="space-y-2 max-h-96 overflow-y-auto">
                {transactions.map((trans, i) => (
                  <div
                    key={i}
                    className={`flex items-center gap-3 p-3 rounded-xl group transition-all
                      ${trans.isDuplicate ? 'bg-amber-50 dark:bg-amber-900/20 opacity-60' : trans.selected ? 'bg-gray-50 dark:bg-gray-700' : 'bg-gray-50 dark:bg-gray-700 opacity-50'}`}
                  >
                    {/* Checkbox */}
                    <button
                      onClick={() => toggleTransactionSelection(i)}
                      className={`w-5 h-5 rounded flex items-center justify-center flex-shrink-0 border-2 transition-colors
                        ${trans.selected
                          ? 'bg-gray-900 dark:bg-white border-gray-900 dark:border-white'
                          : trans.isDuplicate
                            ? 'border-amber-300 dark:border-amber-600 bg-amber-100 dark:bg-amber-900/30'
                            : 'border-gray-300 dark:border-gray-500 bg-white dark:bg-gray-600'
                        }`}
                    >
                      {trans.selected && (
                        <svg className="w-3 h-3 text-white dark:text-gray-900" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={3} d="M5 13l4 4L19 7" />
                        </svg>
                      )}
                    </button>

                    <button
                      onClick={() => toggleTransactionType(i)}
                      className={`w-8 h-8 rounded-full flex items-center justify-center flex-shrink-0 transition-colors hover:ring-2 hover:ring-offset-1
                      ${trans.type === 'income' ? 'bg-emerald-100 dark:bg-emerald-900/40 hover:ring-emerald-400' : 'bg-rose-100 dark:bg-rose-900/40 hover:ring-rose-400'}`}
                      title={language === 'pt' ? 'Clique para inverter tipo' : 'Click to swap type'}
                    >
                      <svg className={`w-4 h-4 ${trans.type === 'income' ? 'text-emerald-600 dark:text-emerald-400' : 'text-rose-600 dark:text-rose-400'}`}
                        fill="none" stroke="currentColor" viewBox="0 0 24 24">
                        {trans.type === 'income' ? (
                          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M7 11l5-5m0 0l5 5m-5-5v12" />
                        ) : (
                          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 13l-5 5m0 0l-5-5m5 5V6" />
                        )}
                      </svg>
                    </button>

                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2 flex-wrap">
                        <p className="text-sm font-medium text-gray-900 dark:text-white break-words" title={trans.description}>{trans.description}</p>
                        {trans.isInstallment && (
                          <span className="px-1.5 py-0.5 bg-blue-100 dark:bg-blue-900/40 text-blue-700 dark:text-blue-300 text-xs rounded">
                            {trans.installmentCurrent}/{trans.installmentTotal}
                          </span>
                        )}
                        {trans.autoGenerated && (
                          <span className="px-1.5 py-0.5 bg-purple-100 dark:bg-purple-900/40 text-purple-700 dark:text-purple-300 text-xs rounded">
                            {language === 'pt' ? 'auto' : 'auto'}
                          </span>
                        )}
                        {trans.isDuplicate && (
                          <span className="px-1.5 py-0.5 bg-amber-100 dark:bg-amber-900/40 text-amber-700 dark:text-amber-300 text-xs rounded">
                            {language === 'pt' ? 'duplicada' : 'duplicate'}
                          </span>
                        )}
                      </div>
                      <p className="text-xs text-gray-500 dark:text-gray-400">
                        {new Date(trans.date).toLocaleDateString(locale)}
                      </p>
                    </div>

                    <select
                      value={trans.category}
                      onChange={(e) => updateTransactionCategory(i, e.target.value)}
                      className={`text-xs px-2 py-1 rounded-lg border-0 focus:ring-0
                        ${trans.autoCategory ? 'bg-blue-50 dark:bg-blue-900/40 text-blue-700 dark:text-blue-300' : 'bg-gray-100 dark:bg-gray-600 text-gray-700 dark:text-gray-200'}`}
                    >
                      {categories[trans.type].map(cat => (
                        <option key={cat} value={cat}>{cat}</option>
                      ))}
                    </select>

                    <span className={`text-sm font-medium whitespace-nowrap
                      ${trans.type === 'income' ? 'text-emerald-600 dark:text-emerald-400' : 'text-rose-600 dark:text-rose-400'}`}>
                      {trans.type === 'income' ? '+' : '-'}{formatCurrency(trans.amount)}
                    </span>

                    <button
                      onClick={() => removeTransaction(i)}
                      className="opacity-0 group-hover:opacity-100 p-1 text-gray-400 hover:text-rose-500 dark:hover:text-rose-400 transition-all"
                    >
                      <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                      </svg>
                    </button>
                  </div>
                ))}
              </div>

              {error && (
                <div className="p-4 bg-rose-50 dark:bg-rose-900/30 border border-rose-200 dark:border-rose-800 rounded-xl">
                  <p className="text-sm text-rose-600 dark:text-rose-400">{error}</p>
                </div>
              )}
            </div>
          )}

          {step === 'done' && (
            <div className="text-center py-8">
              <div className="w-16 h-16 bg-emerald-100 dark:bg-emerald-900/50 rounded-full flex items-center justify-center mx-auto mb-4">
                <svg className="w-8 h-8 text-emerald-600 dark:text-emerald-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
                </svg>
              </div>
              <h3 className="text-xl font-semibold text-gray-900 dark:text-white mb-2">{t('import.complete')}</h3>
              <p className="text-gray-500 dark:text-gray-400">
                {t('import.successMessage', { count: transactions.length })}
              </p>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="px-6 py-4 border-t border-gray-100 dark:border-gray-700 bg-gray-50 dark:bg-gray-900">
          {step === 'upload' && (
            <button
              onClick={handleParse}
              disabled={!file || loading}
              className="w-full py-3 bg-gray-900 dark:bg-gray-100 text-white dark:text-gray-900 rounded-xl font-medium
                hover:bg-gray-800 dark:hover:bg-gray-200 disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              {loading ? t('import.processing') : t('common.continue')}
            </button>
          )}

          {step === 'preview' && (
            <button
              onClick={handleImport}
              disabled={selectedCount === 0 || importing}
              className="w-full py-3 bg-emerald-500 text-white rounded-xl font-medium
                hover:bg-emerald-600 disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              {importing ? t('import.importing') : t('import.importBtn', { count: selectedCount })}
            </button>
          )}

          {step === 'done' && (
            <button
              onClick={handleClose}
              className="w-full py-3 bg-gray-900 dark:bg-gray-100 text-white dark:text-gray-900 rounded-xl font-medium hover:bg-gray-800 dark:hover:bg-gray-200 transition-colors"
            >
              {t('common.done')}
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
